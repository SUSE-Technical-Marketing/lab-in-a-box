#!/usr/bin/env python3
# scripts/build_man_pages.py: the man pages it generates from each command's own --help. Verifies that every
# command the installer deploys gets one, that each page carries the sections man expects, that NAME holds a real
# summary rather than a usage string, and that the roff specials in a help text are escaped. The pages are written
# to the directory given as argv[1], which 127_man_pages.sh then renders with groff. Run from that script, in its
# own container — see tests/run_tests.sh.
import re
import subprocess
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_REPO / "libs"))
sys.path.insert(0, str(_REPO / "scripts"))

import importlib.util  # noqa: E402
from importlib.machinery import SourceFileLoader  # noqa: E402

_loader = SourceFileLoader("build_man_pages", str(_REPO / "scripts" / "build_man_pages.py"))
_spec = importlib.util.spec_from_loader("build_man_pages", _loader)
bmp = importlib.util.module_from_spec(_spec)
_loader.exec_module(bmp)

failures = []


def check(desc, cond):
    if not cond:
        failures.append(desc)
        print("FAIL:", desc)


out_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/man-pages-check")

# ── the command list still matches what the installer deploys ───────────────
installer = (_REPO / "install_automation_node_scripts.sh").read_text()

# The four copied by name, then the _TOOLING list, then the two under sbin.
tooling = re.search(r'_TOOLING="(.*?)"', installer, re.S)
check("the installer still declares a _TOOLING list", tooling is not None)
installed = {"setup_lab.py", "setup_vm.py", "destroy_vm.py", "destroy_lab.py"}
if tooling:
    installed |= set(tooling.group(1).split())
installed |= {"lab-builder-helper", "lab-builder-passwd"}

# lab_schema and the add-on installers are commands too, but schema_versions.py is a contributor tool the
# installer does not deploy; the set above is exactly what it does.
missing = sorted(installed - set(bmp.COMMANDS))
check("every command the installer deploys has a man page: missing {}".format(missing), not missing)
extra = sorted(set(bmp.COMMANDS) - installed)
check("no page is declared for a command the installer does not deploy: {}".format(extra), not extra)
check("the section-8 pages are the two commands installed under sbin",
      {c for c, s in bmp.COMMANDS.items() if s == 8} == {"lab-builder-helper", "lab-builder-passwd"})
for section, directory in bmp.INSTALL_DIRS.items():
    check("section {} commands are read from {}".format(section, directory),
          str(directory).startswith("/usr/local/"))

# ── generate every page from the checkout and inspect it ────────────────────
errors = bmp.build(sorted(bmp.COMMANDS), None, out_dir, section=None, dry_run=False)
# Built with source_dir=None (--installed), nothing is deployed in this container, so every command should have
# been reported as missing rather than crashing: that is the error path this asserts.
check("a command that is not installed is reported, not crashed on", len(errors) == len(bmp.COMMANDS))
check("...and the report names the command and the path", errors and "does not exist" in errors[0])

errors = bmp.build(sorted(bmp.COMMANDS), _REPO / "scripts", out_dir)
check("every page is generated from the checkout with no error: {}".format(errors), not errors)

# An installed tree holds the helper under the command's own name, a checkout under its source name, and the page
# has to build from either: it did not, and lab-builder-helper had no page on every installed node.
import os  # noqa: E402

installed_dir = out_dir / "as-installed"
os.makedirs(str(installed_dir))
source = (_REPO / "scripts" / bmp.SOURCE_NAMES["lab-builder-helper"]).read_text()
renamed = installed_dir / "lab-builder-helper"
renamed.write_text(source)
os.chmod(str(renamed), 0o755)
errors = bmp.build(["lab-builder-helper"], installed_dir, out_dir)
check("the helper's page builds from a tree that holds it under its installed name: {}".format(errors),
      not errors and (out_dir / "man8" / "lab-builder-helper.8").is_file())

for command, section in sorted(bmp.COMMANDS.items()):
    page = out_dir / "man{}".format(section) / "{}.{}".format(command, section)
    check("{}: its page was written".format(command), page.is_file())
    if not page.is_file():
        continue
    text = page.read_text(encoding="utf-8")
    check("{}: says it is generated, so nobody edits it by hand".format(command),
          text.startswith(".\\\" Generated by build_man_pages.py"))
    check("{}: has a .TH line in section {}".format(command, section),
          "\n.TH " in text and " {} ".format(section) in text.split("\n")[1])
    for heading in (".SH NAME", ".SH SEE ALSO"):
        check("{}: has a {} section".format(command, heading.split()[-1]), heading in text)
    name_line = text.split(".SH NAME\n", 1)[1].split("\n", 1)[0]
    check("{}: NAME is '<command> \\- <summary>'".format(command), " \\- " in name_line)
    summary = name_line.split(" \\- ", 1)[1]
    check("{}: NAME carries a summary, not a usage string ({!r})".format(command, summary),
          not summary.lower().startswith(("usage:", command.lower() + " ")))
    check("{}: NAME is one line and not empty".format(command), 0 < len(summary) <= 140)
    check("{}: the body is unfilled, so the help's own column alignment survives".format(command),
          ".nf\n" in text and ".fi\n" in text)
    check("{}: SEE ALSO points at the documentation site".format(command),
          "suse-technical-marketing.github.io/lab-in-a-box" in text)
    check("{}: no line starts with an unescaped roff request".format(command),
          not any(ln.startswith(".") and not ln.startswith((".\\\"", ".TH", ".SH", ".nf", ".fi"))
                  for ln in text.splitlines()))

# ── roff escaping and summary extraction, on their own ──────────────────────
check("a leading '.' in a help line is made literal", bmp.roff_escape(".not-a-request") == "\\&.not-a-request")
check("a leading apostrophe too", bmp.roff_escape("'quoted'") == "\\&'quoted'")
check("a backslash is escaped", bmp.roff_escape("a\\b") == "a\\eb")
check("an ordinary line is untouched", bmp.roff_escape("  --flag  does a thing") == "  --flag  does a thing")

check("the '<command> — summary' opening becomes the summary alone",
      bmp.summary_of("mycmd.py — does a thing.\n\nUsage: mycmd.py", "mycmd.py") == "does a thing")
check("a '<command>: summary' opening too",
      bmp.summary_of("mycmd.py: does a thing\n", "mycmd.py") == "does a thing")
check("a help text that opens with its usage block looks past it for the summary",
      bmp.summary_of("Usage: mycmd.py <x>\n\nDoes a thing with <x>.\n", "mycmd.py") == "Does a thing with <x>")
check("a bare invocation paragraph is skipped as well",
      bmp.summary_of("mycmd.py USER\nmycmd.py --list\n\nManages users.\n", "mycmd.py") == "Manages users")
check("the opening sentence is taken, not the whole paragraph",
      bmp.summary_of("Does one thing. Then it does another thing entirely.\n", "x") == "Does one thing")
_long = "Does " + "a very long thing " * 12
check("an over-long summary is cut with a marker rather than running on",
      bmp.summary_of(_long, "x").endswith("...") and len(bmp.summary_of(_long, "x")) <= 110)
check("a help text with nothing usable still yields the command's name",
      bmp.summary_of("", "mycmd.py") == "mycmd.py")

# The sections a help text declares become the man sections an operator expects to find.
_help = "x — does things.\n\nUsage:\n    x <a>\n\nOptions:\n    --flag  a flag\n\nExamples:\n    x 1\n"
_sections = dict(bmp.sections_of(_help, "x"))
check("'Usage:' becomes SYNOPSIS", "SYNOPSIS" in _sections)
check("'Options:' becomes OPTIONS", "OPTIONS" in _sections)
check("'Examples:' becomes EXAMPLES", "EXAMPLES" in _sections)
check("the opening paragraph stays in DESCRIPTION", "DESCRIPTION" in _sections)
check("a heading the map does not know keeps its own words, upper-cased",
      "GOTCHAS" in dict(bmp.sections_of("x — y.\n\nGotchas:\n    careful\n", "x")))

# --list is what an operator and the installer both read the command set from.
listed = subprocess.run([sys.executable, str(_REPO / "scripts" / "build_man_pages.py"), "--list"],
                        stdout=subprocess.PIPE)
check("--list exits 0", listed.returncode == 0)
check("--list prints every command with its section",
      len(listed.stdout.decode().strip().splitlines()) == len(bmp.COMMANDS))

if failures:
    print("{} check(s) failed".format(len(failures)))
    sys.exit(1)
print("all man-page checks passed")
